"""Generate pinned native movie patches; rejects mismatched or overlapping edits."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def movie_patch(path, extracted):
    data = json.loads(path.read_text())
    suffix = data['file'].replace('\\', '/').split('/')[-1]
    if suffix not in ('corvo_pause_menu.iggy', 'emily_pause_menu.iggy', 'main_menu.iggy'):
        raise ValueError('Unexpected native movie')
    original = (extracted / ('ui_' + suffix)).read_bytes()
    if len(original) != data['size']:
        raise ValueError('Native movie size differs from patch manifest')
    patched = bytearray(original)
    occupied = set()
    edits = []
    for edit in data['patches']:
        old, new = bytes.fromhex(edit['old']), bytes.fromhex(edit['new'])
        offset = edit['offset']
        if not old or len(old) != len(new) or offset < 0 or offset + len(old) > len(original):
            raise ValueError('Invalid same-size native movie edit')
        span = set(range(offset, offset + len(old)))
        if occupied.intersection(span) or original[offset:offset+len(old)] != old:
            raise ValueError('Native movie edit overlaps or differs from pinned source bytes')
        occupied.update(span)
        patched[offset:offset+len(old)] = new
        edits.append((offset, old, new))
    archived = path.parent / ('ui_' + suffix)
    if archived.read_bytes() != patched:
        raise ValueError('Archived patched movie differs from reviewed edits')
    return suffix, original, bytes(patched), edits


def generate(patch_dir, extracted):
    out = ['#pragma once',
           '// Generated by tools/gen_menu_patches.py; complete extracted movie hashes pin ownership.',
           '#include <array>', '#include <cstddef>', 'namespace d2vr::menu_patches {',
           'struct Edit {std::size_t offset;const unsigned char* old_bytes;const unsigned char* new_bytes;std::size_t size;};',
           'struct Movie {const char* suffix;std::size_t size;const Edit* edits;std::size_t count;std::array<unsigned char,32> original_sha256,patched_sha256;};']
    movies = []
    def array(value): return ','.join('0x%02x' % byte for byte in value)
    paths = sorted(patch_dir.glob('*.iggy.patch.json'))
    if len(paths) != 3:
        raise ValueError('Expected the three reviewed native menu movie patches')
    for i, path in enumerate(paths):
        suffix, original, patched, edits = movie_patch(path, extracted)
        generated = []
        for j, (offset, old, new) in enumerate(edits):
            out.append(f'inline constexpr unsigned char m{i}_o{j}[]={{'+array(old)+'};')
            out.append(f'inline constexpr unsigned char m{i}_n{j}[]={{'+array(new)+'};')
            generated.append('{%d,m%d_o%d,m%d_n%d,%d}' % (offset, i, j, i, j, len(old)))
        out.append(f'inline constexpr Edit m{i}_edits[]={{'+','.join(generated)+'};')
        movies.append('{"%s",%d,m%d_edits,%d,{%s},{%s}}' % (suffix, len(original), i, len(edits), array(hashlib.sha256(original).digest()), array(hashlib.sha256(patched).digest())))
    out.append('inline constexpr Movie movies[]={'+','.join(movies)+'};')
    out.append('} // namespace d2vr::menu_patches')
    return '\n'.join(out)+'\n'


if __name__ == '__main__':
    (ROOT/'src/menu_patches.hpp').write_text(generate(ROOT/'artifacts/menu-re/patched', ROOT/'artifacts/menu-re/ex'))
    print('Generated three byte-verified native menu movie patches with SHA256 ownership')
