"""Write tests/player_rig_fixture.hpp (bind skeletons from the offline asset pack) for body IK checks."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / 'artifacts/fullbody-assets/pack'


def skeleton(name, var, runtime=False):
    s = json.loads((PACK / f'skeleton_{name}.json').read_text())
    rows = []
    for n, p, b in zip(s['joint_names'], s['parents'], s['local_bind']):
        q, t = b['rot_xyzw'], b['trans']
        rows.append('    {"%s",%d,{%.9g,%.9g,%.9g,%.9g},{%.9g,%.9g,%.9g}},' % (n, p, *q, *t))
    if runtime:  # constant-initialized: see the FixtureJoints comment in src/player_rig_data.hpp
        return ('inline constexpr FixtureJoint %sJoints[]={\n%s\n};\n'
                'inline constexpr FixtureJoints %s{%sJoints,std::size(%sJoints)};\n' % (var, '\n'.join(rows), var, var, var))
    return 'inline const std::vector<FixtureJoint> %s={\n%s\n};\n' % (var, '\n'.join(rows))


# Native animated arm poses (arm-model space, renderer upload source) captured read-only in game.
NATIVE = [('sword_idle', 'artifacts/native-sword-idle-source-v85.json/pose-0020.json'),
          ('capture_23072', 'artifacts/native-fullbody-rig-23072-readonly.json')]


def native_poses():
    rows = []
    for label, path in NATIVE:
        arms = json.loads((ROOT / path).read_text(encoding='utf-8-sig'))['body_samples'][0]['arms']
        for arm in arms:
            assert len(arm['sampled_joints']) == 69 and arm['pose_state'] == 3
            joints = []
            for j in arm['sampled_joints']:
                c = j['rotation_columns']
                joints.append('{%s,%s}' % ('{' + ','.join('%.7g' % v for col in c for v in col) + '}',
                                           '{' + ','.join('%.7g' % v for v in j['position']) + '}'))
            rows.append('    {"%s",%d,{%s}},' % (label, 0 if arm['side'] == 'left' else 1, ','.join(joints)))
    return ('struct FixtureNativeJoint {double columns[9];double t[3];};\n'
            'struct FixtureNativeArm {const char* label;int side;FixtureNativeJoint joints[69];};\n'
            'inline const FixtureNativeArm kFixtureNativeArms[]={\n%s\n};\n' % '\n'.join(rows))


out = ['// Generated by tools/gen_rig_fixture.py from the offline Dishonored 2 player asset pack.',
       '// Local bind transforms (quaternion xyzw, translation) verified against live inverse binds.',
       '#pragma once', '#include <vector>',
       'struct FixtureJoint {const char* name;int parent;double q[4];double t[3];};',
       skeleton('body', 'kFixtureBody'), skeleton('left_arm', 'kFixtureLeftArm'),
       skeleton('right_arm', 'kFixtureRightArm'), native_poses()]
(ROOT / 'tests/player_rig_fixture.hpp').write_text('\n'.join(out))
print('wrote tests/player_rig_fixture.hpp')
# Runtime copy for the DLL: bind skeletons only, namespaced (no captured poses).
runtime = ['// Generated by tools/gen_rig_fixture.py: player bind skeletons for the in-game full-body solver.',
           '#pragma once', '#include <cstddef>', '#include <iterator>', 'namespace d2vr::fullbody::data {',
           'struct FixtureJoint {const char* name;int parent;double q[4];double t[3];};',
           "// constexpr tables, not std::vector: a dynamic initializer here is not ordered before the DLL's global",
           '// full-body driver under clang-cl (it ran after it and the skeleton was empty), constant initialization always is.',
           'struct FixtureJoints {const FixtureJoint* first;std::size_t count;',
           '    constexpr const FixtureJoint* begin() const {return first;}constexpr const FixtureJoint* end() const {return first+count;}',
           '    constexpr std::size_t size() const {return count;}};',
           skeleton('body', 'kBody', True), skeleton('left_arm', 'kLeftArm', True), skeleton('right_arm', 'kRightArm', True),
           '} // namespace d2vr::fullbody::data']
(ROOT / 'src/player_rig_data.hpp').write_text('\n'.join(runtime) + '\n', encoding='utf-8')
print('wrote src/player_rig_data.hpp')
