"""Write the Death of the Outsider candidate manifest the launcher embeds (artifacts/doto/repair-vNNNN-test-candidate.json).

Same schema as the Dishonored 2 manifests (artifacts/repair-vNNNN-test-candidate.json); game_sha256 is DOTO's exe.
The DLL must already be in build/doto/ (tools/doto/build-doto.cmd).

    python tools/doto/make_candidate.py 145708 --state "first DOTO candidate" --sim-evidence "boot3: ..." [--blocked]
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOTO_SHA = "be73d979fdb5a6eacbcd385944c6060b97c997d06ab9d72fb39f275a866b955d"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("version", type=int)
    ap.add_argument("--state", required=True)
    ap.add_argument("--sim-evidence", default="none")
    ap.add_argument("--limitation", action="append", default=[])
    ap.add_argument("--blocked", action="store_true")
    a = ap.parse_args()
    name = f"d2vr_render_probe_arm_v{a.version}.dll"
    dll = ROOT / "build" / "doto" / name
    data = dll.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain", "src", "tools/doto"], capture_output=True, text=True, cwd=ROOT).stdout.strip())
    manifest = {
        "schema": 1, "version": a.version, "state": a.state, "dll_name": name, "sha256": sha, "dll_sha256": sha,
        "dll_bytes": len(data), "game_sha256": DOTO_SHA, "game": "Dishonored: Death of the Outsider (Dishonored_DO.exe)",
        "source_commit": commit, "source_dirty": dirty,
        "build_host": f"Windows MSVC x64 (tools/doto/build-doto.cmd {a.version}: tools/doto/port.py from src/)",
        "full_required_build_passed": False, "launch_blocked": a.blocked, "headset_validated": False, "headset_tested": False,
        "sim_evidence": a.sim_evidence,
        "limitations": ["Not headset-tested.", "Generated by the DOTO port (tools/doto); see docs/DOTO-VR.md.", *a.limitation],
    }
    out = ROOT / "artifacts" / "doto" / f"repair-v{a.version}-test-candidate.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(out, sha)


if __name__ == "__main__":
    main()
