"""Write tests/player_clip_fixture.hpp: decoded native game clips (local joint TRS per frame) for
the body/arm blend checks. Clips come straight from the game's .md6anim files via decode_md6anim.
"""
from pathlib import Path
import numpy as np
import decode_md6anim as m

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / 'artifacts/fullbody-assets/anims/raw/models/characters/player/_animations_'
# (fixture name, [body, left arm, right arm] relative paths under _animations_)
MOVES = [
    ('land_big', ['corvo/body/ply_body_generic_jumpland_big', 'corvo/leftarm/ply_leftarm_generic_jumpland_big',
                  'corvo/rightarm/ply_rightarm_generic_jumpland_big']),
    ('assassination_back', ['corvo/body/ply_body_generic_corvo_assassination_back',
                            'corvo/leftarm/ply_leftarm_generic_corvo_assassination_back',
                            'corvo/rightarm/ply_rightarm_generic_corvo_assassination_back']),
    ('vault', ['corvo/body/ply_body_generic_vault_a', 'corvo/leftarm/ply_leftarm_generic_vault_a',
               'corvo/rightarm/ply_rightarm_generic_vault_a']),
    ('guard_fatality', ['common/body/ply_body_generic_npc_guard_fatality',
                        'common/leftarm/ply_leftarm_generic_npc_guard_fatality',
                        'common/rightarm/ply_rightarm_generic_npc_guard_fatality']),
    ('choke', ['corvo/body/ply_body_generic_corvo_choke_loop', 'corvo/leftarm/ply_leftarm_generic_corvo_choke_loop',
               'corvo/rightarm/ply_rightarm_generic_corvo_choke_loop']),
]


def clip(path):
    d = m.decode(str(RAW / (path + '.md6anim')))
    q, t = np.asarray(d['Q'], np.float64), np.asarray(d['T'], np.float64)
    data = np.concatenate([q, t], axis=2)  # frames x joints x 7
    return d['frame_rate'], data


out = ['// Generated by tools/gen_clip_fixture.py from the game\'s .md6anim files (decode_md6anim).',
       '// Local joint transforms per frame: qx,qy,qz,qw,tx,ty,tz; joint order = pack skeleton order.',
       '#pragma once',
       'struct FixtureClipPart {int frames;int joints;double fps;const float* data;};',
       'struct FixtureClip {const char* name;FixtureClipPart part[3];}; // body, left arm, right arm']
parts = []
for name, paths in MOVES:
    entries = []
    for k, p in enumerate(paths):
        fps, data = clip(p)
        var = 'kClip_%s_%d' % (name, k)
        out.append('inline const float %s[]={%s};' % (var, ','.join('%.6ef' % v for v in data.ravel())))
        entries.append('{%d,%d,%g,%s}' % (data.shape[0], data.shape[1], fps, var))
    parts.append('    {"%s",{%s}},' % (name, ','.join(entries)))
out.append('inline const FixtureClip kFixtureClips[]={\n%s\n};' % '\n'.join(parts))
(ROOT / 'tests/player_clip_fixture.hpp').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote tests/player_clip_fixture.hpp', [n for n, _ in MOVES])
